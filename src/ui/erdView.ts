import { t } from '../i18n';
import type { ErConstraint } from '../viz/erd';
import { cx, isDark } from '../theme';
import { once } from '../viz/memo';
import { h, nodes } from './dom';

let seq = 0;
/** A failed chunk import is not cached: the next tab open retries. */
const mermaid = once(() => import('mermaid').then((m) => m.default));

/** Renders the Mermaid definition to SVG text in the app's current theme (initialize per render, so a theme switch is picked up). */
export async function erdSvg(definition: string): Promise<string> {
  const m = await mermaid();
  m.initialize({ startOnLoad: false, securityLevel: 'strict', theme: isDark() ? 'dark' : 'default' });
  return (await m.render(`erd-${++seq}`, definition)).svg;
}

export function drawErd(host: HTMLElement, svg: string): void {
  // Mermaid sets its own width/max-width inline; the wrapper scrolls instead of squeezing the diagram.
  const figure = h('div', { class: 'overflow-auto [&_svg]:h-auto' });
  // Only innerHTML in the app: SVG generated by Mermaid (strict mode) from sanitised schema identifiers (mermaidName).
  figure.innerHTML = svg;
  // Name on the <svg> itself (not role=img on the wrapper), so the table names inside stay readable.
  figure.querySelector('svg')?.setAttribute('aria-label', t('erd.aria'));
  host.append(
    h('p', { class: 'muted' },
      `${t('erd.intro')} `, h('code', {}, '||'), ` ${t('erd.one')} · `, h('code', {}, '|o'), ` ${t('erd.zeroOne')} · `,
      h('code', {}, 'o{'), ` ${t('erd.many')}. ${t('erd.bold')}`),
    figure,
  );
}

const BADGE = 'rounded bg-code px-1 text-xs font-semibold ring-1 ring-line';

/** "AIRPORT · SEAPORT" under a column name: hidden until the values are in, and for columns with too many of them. */
export function valuesLine(values: Promise<Record<string, string[]>> | undefined, column: string, cls = ''): HTMLElement {
  const el = h('span', { class: cx('block text-xs text-muted', cls), hidden: true });
  values?.then((v) => {
    if (!v[column]) return;
    el.textContent = v[column].join(' · ');
    el.hidden = false;
  }, () => {});
  return el;
}

/**
 * PK / UK / FK badges of one column. An FK to an unlocked table shows `→ table.column` (a button when `onRef` is given);
 * to a locked table only "locked table", so the Data page and the Columns tab never name what is not open yet.
 */
export function keyBadges(cons: ErConstraint[], table: string, column: string, unlocked: Set<string>, onRef?: (table: string) => void): Node[] {
  const mine = cons.filter((c) => c.table === table && c.column === column);
  const out: Node[] = [];
  if (mine.some((c) => c.kind === 'PRIMARY KEY')) out.push(h('span', { class: BADGE }, 'PK'));
  if (mine.some((c) => c.kind === 'UNIQUE')) out.push(h('span', { class: BADGE }, 'UK'));
  for (const c of mine.filter((x) => x.kind === 'FOREIGN KEY' && x.refTable)) {
    const ref = `${c.refTable}.${c.refColumn ?? ''}`;
    out.push(h('span', { class: 'inline-flex items-center gap-1' }, h('span', { class: BADGE }, 'FK →'), ...nodes(
      !unlocked.has(c.refTable!) ? h('span', { class: 'text-sm text-muted' }, t('data.refLocked'))
        : onRef ? h('button', { type: 'button', class: 'px-1.5 py-0 font-mono text-sm', onclick: () => onRef(c.refTable!) }, ref)
          : h('code', {}, ref))));
  }
  return out;
}
