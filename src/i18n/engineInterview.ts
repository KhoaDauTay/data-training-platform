export const IV_DICT = { vi: vi as Record<IvKey, string>, en };

export function ivText(lang: Lang, locale: string, key: IvKey, params: Params = {}): string {
  return IV_DICT[lang][key].replace(/\{(\w+)\}/g, (m, name: string) => {
    const v = params[name];
    return v === undefined ? m : typeof v === 'number' ? v.toLocaleString(locale) : v;
  });
}
