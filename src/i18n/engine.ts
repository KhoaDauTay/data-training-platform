export const ENGINE_DICT = { vi: vi as Record<EngineKey, string>, en };

export function engineText(lang: Lang, locale: string, key: EngineKey, params: Params = {}): string {
  return ENGINE_DICT[lang][key].replace(/\{(\w+)\}/g, (m, name: string) => {
    const v = params[name];
    return v === undefined ? m : typeof v === 'number' ? v.toLocaleString(locale) : v;
  });
}
