export const BEST_DICT = { vi: vi as Record<BestKey, string>, en };

export function bestText(lang: Lang, locale: string, key: BestKey, params: Params = {}): string {
  return BEST_DICT[lang][key].replace(/\{(\w+)\}/g, (m, name: string) => {
    const v = params[name];
    return v === undefined ? m : typeof v === 'number' ? v.toLocaleString(locale) : v;
  });
}
