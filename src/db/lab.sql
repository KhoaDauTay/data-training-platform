  SELECT i, 1 + floor(random() * 300)::int AS cid, (ARRAY[1, 1, 2, 3, 3, 3, 4, 5, 5])[1 + floor(random() * 9)::int] AS store,
         random() AS rk, random() AS rt, 420 + floor(random() * 900)::int AS mins, random() AS ra
  FROM generate_series(1, 25000) AS i
)
INSERT INTO events_big (id, customer_id, store_id, kind, ts, amount_vnd)
SELECT x.i, x.cid, x.store, k.kind,
       d.first + floor(x.rt * (DATE '2026-10-31' - d.first + 1))::int + x.mins * interval '1 minute',
       CASE WHEN k.kind IN ('paid', 'refund') THEN 1000 * (20 + floor(x.ra * 1980)::int) END
FROM x
JOIN customers c ON c.id = x.cid
CROSS JOIN LATERAL (SELECT greatest(c.signup_date, DATE '2026-01-01') AS first) d
CROSS JOIN LATERAL (SELECT CASE WHEN x.rk < 0.30 THEN 'visit' WHEN x.rk < 0.70 THEN 'view' WHEN x.rk < 0.85 THEN 'add_to_cart'
