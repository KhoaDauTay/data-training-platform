-- v24 R0b (schema-perf-v24 S2, L351): events_big, the table the performance drills (General Part 11) need. The tables
-- above are too small (orders: 1,428 rows / 17 pages) for a non-sargable query to cost much more than a good one.
--   25,000 rows: under ANALYZE's 30,000-row sample, so ANALYZE reads every row and plan costs are the same on every boot
--     (a bigger table needs default_statistics_target raised around its ANALYZE, as seed.sql does for container_events)
--   index (customer_id, ts); deliberately NO index on kind (a drill adds it: 'refund' is about 1 % of rows)
--   store_id has no index on purpose (a drill on "index your foreign key"); ts is never before the customer's signup,
--   always in 2026-01-01..2026-10-31 between 07:00 and 21:59; amount_vnd only on 'paid' and 'refund' (the CHECK says so)
CREATE TABLE events_big (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id int NOT NULL,
  store_id int NOT NULL,
  kind text NOT NULL CHECK (kind IN ('visit', 'view', 'add_to_cart', 'checkout', 'paid', 'refund')),
  ts timestamp NOT NULL,
  amount_vnd int CHECK (amount_vnd > 0),
  CHECK ((kind IN ('paid', 'refund')) = (amount_vnd IS NOT NULL))
);
