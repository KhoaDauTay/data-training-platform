// ui-ux-v6 S2: one-off generator of src/art/coast.ts, the route map's land from Natural Earth 1:110m (public domain).
// node scripts/coast.mjs [ne_110m_land.geojson]   (no argument: downloads SRC; source, commit and date in assets/THIRD_PARTY.md)
// Plate carrée: x = (lon - LON0) * K, y = (LAT0 - lat) * K, frame 1000 × 400 (lon -12..254.7, lat 62..-44.7). Polygons are
// clipped to the frame plus a margin (so no clipped edge is ever stroked on screen), simplified (Douglas–Peucker) and
// written as integer relative path commands.
import { readFileSync, writeFileSync } from 'node:fs';

const SRC = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/693f11422f4e08d2da4566b854dda53eb7c39fb3/geojson/ne_110m_land.geojson';
const LON0 = -12, LAT0 = 62, K = 3.75, W = 1000, H = 400, PAD = 8, TOL = 0.5, MIN_AREA = 6;

const geo = process.argv[2] ? JSON.parse(readFileSync(process.argv[2], 'utf8')) : await (await fetch(SRC)).json();

const rings = [];
for (const f of geo.features) {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) for (const ring of poly) {
    // the Americas (wholly west of 20°W) move east of the antimeridian, so the Pacific is one sea
    const shift = Math.max(...ring.map(([lon]) => lon)) < -20 ? 360 : 0;
    rings.push(ring.map(([lon, lat]) => [(lon + shift - LON0) * K, (LAT0 - lat) * K]));
  }
}

/** Sutherland–Hodgman against one edge of the padded frame. */
function clipEdge(pts, inside, cut) {
  const out = [];
  for (let i = 0; i < pts.length; i++) {
    const a = pts[i], b = pts[(i + 1) % pts.length];
    if (inside(a)) { out.push(a); if (!inside(b)) out.push(cut(a, b)); } else if (inside(b)) out.push(cut(a, b));
  }
  return out;
}
const atX = (x) => (a, b) => [x, a[1] + ((b[1] - a[1]) * (x - a[0])) / (b[0] - a[0])];
const atY = (y) => (a, b) => [a[0] + ((b[0] - a[0]) * (y - a[1])) / (b[1] - a[1]), y];
function clip(pts) {
  pts = clipEdge(pts, (p) => p[0] >= -PAD, atX(-PAD));
  pts = clipEdge(pts, (p) => p[0] <= W + PAD, atX(W + PAD));
  pts = clipEdge(pts, (p) => p[1] >= -PAD, atY(-PAD));
  return clipEdge(pts, (p) => p[1] <= H + PAD, atY(H + PAD));
}

function dp(pts, tol) {
  if (pts.length < 3) return pts;
  const [a, b] = [pts[0], pts[pts.length - 1]];
  let best = 0, at = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const p = pts[i];
    const dx = b[0] - a[0], dy = b[1] - a[1];
    const len = Math.hypot(dx, dy);
    const d = len ? Math.abs(dy * p[0] - dx * p[1] + b[0] * a[1] - b[1] * a[0]) / len : Math.hypot(p[0] - a[0], p[1] - a[1]);
    if (d > best) { best = d; at = i; }
  }
  return best > tol ? [...dp(pts.slice(0, at + 1), tol).slice(0, -1), ...dp(pts.slice(at), tol)] : [a, b];
}
const area = (pts) => Math.abs(pts.reduce((s, p, i) => { const q = pts[(i + 1) % pts.length]; return s + p[0] * q[1] - q[0] * p[1]; }, 0)) / 2;

let d = '';
let kept = 0;
for (const ring of rings) {
  const c = clip(ring);
  if (c.length < 3 || area(c) < MIN_AREA) continue;
  // a closed ring: split at the far point so DP keeps the ring's shape on both halves
  const far = c.reduce((m, p, i) => (Math.hypot(p[0] - c[0][0], p[1] - c[0][1]) > Math.hypot(c[m][0] - c[0][0], c[m][1] - c[0][1]) ? i : m), 0);
  const s = [...dp(c.slice(0, far + 1), TOL).slice(0, -1), ...dp([...c.slice(far), c[0]], TOL).slice(0, -1)]
    .map(([x, y]) => [Math.round(x), Math.round(y)])
    .filter((p, i, a) => i === 0 || p[0] !== a[i - 1][0] || p[1] !== a[i - 1][1]);
  if (s.length < 3 || area(s) < MIN_AREA) continue;
  kept++;
  d += `M${s[0][0]} ${s[0][1]}` + s.slice(1).map((p, i) => `l${p[0] - s[i][0]} ${p[1] - s[i][1]}`).join('').replace(/l(-?\d+) (-?\d+)/g, (m, x, y) => `l${x}${y.startsWith('-') ? '' : ' '}${y}`) + 'z';
}

const out = `// GENERATED by scripts/coast.mjs from Natural Earth 1:110m land (public domain, assets/THIRD_PARTY.md). Do not edit.
// Plate carrée, x = (lon - (${LON0})) * ${K}, y = (${LAT0} - lat) * ${K}, viewBox ${W} × ${H}; ${kept} rings, fill-rule evenodd.
export const COAST = { lon0: ${LON0}, lat0: ${LAT0}, k: ${K}, w: ${W}, h: ${H} } as const;
export const LAND = '${d}';
`;
writeFileSync(new URL('../src/art/coast.ts', import.meta.url), out);
console.log(`coast.ts: ${kept} rings, ${d.length} chars`);
