// v6 I1: writes src/ui/iconData.ts from scripts/icon-map.json (Phosphor duotone, @phosphor-icons/core, MIT) and
// scripts/icon-custom.json (BoonData, MIT). `node scripts/icons.mjs` writes; `--check` exits 1 if the file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const read = (p) => readFileSync(root + p, 'utf8');
const OUT = 'src/ui/iconData.ts';
const map = JSON.parse(read('scripts/icon-map.json')).icons;
const custom = JSON.parse(read('scripts/icon-custom.json')).icons;
const version = JSON.parse(read('node_modules/@phosphor-icons/core/package.json')).version;

/** Phosphor duotone files are `<svg …>` + `<path d="…" [opacity="0.2"]/>`s only (checked here, not assumed). */
function phosphor(name) {
  const svg = read(`node_modules/@phosphor-icons/core/assets/duotone/${name}-duotone.svg`);
  const body = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  const parts = [...body.matchAll(/<path d="([^"]+)"(?: opacity="([\d.]+)")?\/>/g)];
  if (parts.map((m) => m[0]).join('') !== body) throw new Error(`${name}: unexpected SVG markup`);
  return parts.map(([, d, o]) => (o ? { d, o: Number(o) } : { d }));
}

const both = Object.keys(map).filter((k) => k in custom);
if (both.length) throw new Error(`in both icon-map.json and icon-custom.json: ${both}`);
const names = [...Object.keys(map), ...Object.keys(custom)].sort();
const entries = names.map((n) => `  ${n}: ${JSON.stringify(custom[n] ?? phosphor(map[n][0]))},`);
const text = `// Generated by scripts/icons.mjs: do not edit. Phosphor Icons ${version} duotone (MIT, see icon-map.json) and
// BoonData's own icons in the same grammar (MIT, icon-custom.json). 256 grid; o = fill opacity, s = stroked (16, round).
export interface IconPart { readonly d: string; readonly o?: number; readonly s?: 1 }
export const ICON_DATA = {
${entries.join('\n')}
} as const satisfies Record<string, readonly IconPart[]>;
`;

if (process.argv.includes('--check')) {
  let now = '';
  try { now = read(OUT).replace(/\r\n/g, '\n'); } catch { /* missing = stale */ }
  if (now !== text) { console.error(`${OUT} is stale: run node scripts/icons.mjs`); process.exit(1); }
} else writeFileSync(root + OUT, text);
